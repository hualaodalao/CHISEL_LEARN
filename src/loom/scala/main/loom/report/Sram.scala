package loom.report

/** Behavioral SRAM blocks for the memories the fabric infers.
  *
  * The blocks are planning artifacts: the emitted RTL already contains the
  * inferred memories and is not rewritten to instantiate these modules. They
  * give the integration owner a concrete macro shape per required depth and
  * width, and separate cell area from logic area.
  */
object Sram {
  /** Memories at or above this depth*width are counted as SRAM, matching the
    * threshold used when deciding whether a queue should become a macro.
    */
  val ThresholdBits: Int = 1024

  /** Placeholder SRAM cell density until a real memory compiler is used. */
  val AreaPerBitUm2: Double = 0.6

  def fileName(depth: Int, width: Int): String = s"LmSramSp_${depth}x${width}.sv"

  def moduleName(depth: Int, width: Int): String = s"LmSramSp_${depth}x${width}"

  /** Single-port RAM: one write port and one registered read port. */
  def singlePort(depth: Int, width: Int): String = {
    require(depth >= 2 && (depth & (depth - 1)) == 0, "SRAM depth must be a power of two")
    require(width >= 1, "SRAM width must be >= 1")
    val aw = math.max(1, 32 - Integer.numberOfLeadingZeros(depth - 1))
    val name = moduleName(depth, width)
    s"""// Behavioral SRAM block generated by Loom.
       |// Planning artifact: the fabric RTL keeps its inferred memories.
       |module $name (
       |  input  wire           clk,
       |  input  wire           we,
       |  input  wire [${aw - 1}:0] addr,
       |  input  wire [${width - 1}:0] wdata,
       |  output reg  [${width - 1}:0] rdata
       |);
       |
       |  reg [${width - 1}:0] mem [0:${depth - 1}];
       |
       |  always @(posedge clk) begin
       |    if (we) mem[addr] <= wdata;
       |    rdata <= mem[addr];
       |  end
       |
       |endmodule
       |""".stripMargin
  }
}
